def norm(name):
    pal, rows = S[name]
    rows = [r for r in rows]
    w = max(len(r) for r in rows); assert w <= 16 and len(rows) <= 16, (name, w, len(rows))
    rows = [r.ljust(w, '.') for r in rows]
    for r in rows:
        for ch in r: assert ch == '.' or ch == 'k' or ch in pal, (name, ch)
    # bounding box of filled pixels
    ys = [y for y, r in enumerate(rows) if r.strip('.')]
    xs = [x for r in rows for x, ch in enumerate(r) if ch != '.']
    y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)
    rows = [r[x0:x1+1] for r in rows[y0:y1+1]]
    h, w = len(rows), len(rows[0])
    top, left = (16 - h) // 2, (16 - w) // 2
    grid = ['.' * 16] * top + ['.' * left + r + '.' * (16 - left - w) for r in rows]
    grid += ['.' * 16] * (16 - len(grid))
    assert len(grid) == 16 and all(len(r) == 16 for r in grid)
    return pal, grid

