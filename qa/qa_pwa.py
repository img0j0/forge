from lib import *
# The installable copy: served from a /forge/ path the way GitHub Pages serves it.
U=os.environ.get("FORGE_URL","http://localhost:8765/forge/")
with sync_playwright() as p:
    b=p.chromium.launch(); ctx,pg=newpage(b); pg.set_default_timeout(8000)
    pg.goto(U); pg.wait_for_selector("#titleGo")
    man=pg.evaluate("async()=>{const r=await fetch('manifest.webmanifest');const j=await r.json();const ok=[];for(const i of j.icons){const im=new Image();im.src=i.src;await im.decode();ok.push(im.naturalWidth+'x'+im.naturalHeight)};return [j.name,j.display,j.start_url,ok]}")
    rec("Install","the manifest names Forgelings, opens standalone, and every icon loads",man[0]=="Forgelings" and man[1]=="standalone" and man[3]==["192x192","512x512","512x512"],man)
    rec("Install","the page is the release copy, titled Forgelings",pg.evaluate("document.documentElement.classList.contains('release')") and pg.title()=="Forgelings")
    pg.wait_for_timeout(1500)
    sw=pg.evaluate("async()=>{const r=await navigator.serviceWorker.getRegistration();return r?(r.active?r.active.state:'pending'):null}")
    rec("Offline","the offline helper is installed",sw=="activated",sw)
    first_card(pg); closemodals(pg); n=len(st(pg)["cards"])
    pg.reload(); pg.wait_for_timeout(800)
    rec("Offline","after a reload the page is served under the offline helper",pg.evaluate("!!navigator.serviceWorker.controller"))
    ctx.set_offline(True); pg.reload(); pg.wait_for_timeout(1500); closemodals(pg)
    rec("Offline","with no connection at all, Forge still opens with your Forgelings",len(st(pg)["cards"])==n and pg.is_visible("#view-today") and not pg._errs,(n,pg._errs[:1]))
    ctx.set_offline(False)
    tabto(pg,"settings"); t=pg.inner_text("#view-settings")
    rec("Settings","prototype tools are hidden for real users",not pg.is_visible("details.dev"))
    rec("Settings","the privacy note says nothing is sent anywhere","sends nothing anywhere" in t and "Google" not in t)
    rec("Settings","in a browser tab it explains how to add Forge to the home screen","Put Forgelings on your home screen" in t)
    reqs=[r for r in pg._reqs if not r.startswith(U[:-6])]
    rec("Privacy","no request leaves the site",not reqs,reqs[:3])
    rec("All","no page errors",not pg._errs,pg._errs[:2]); ctx.close()
    ctx,pg=newpage(b); pg.add_init_script("window.matchMedia=(q=>(m=>({matches:/standalone/.test(m)||q(m).matches,media:m,addEventListener(){},removeEventListener(){},addListener(){},removeListener(){}})))(window.matchMedia.bind(window));")
    pg.goto(U); pg.wait_for_selector("#titleGo"); first_card(pg); closemodals(pg); tabto(pg,"settings")
    rec("Settings","once installed, the home-screen tip goes away","Put Forgelings on your home screen" not in pg.inner_text("#view-settings")); ctx.close()
    b.close()
save_results("qa_pwa"); print(sum(r["ok"] for r in RES),"/",len(RES))
